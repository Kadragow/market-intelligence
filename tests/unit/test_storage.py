def _instrument_snapshot() -> InstrumentSnapshot:
    return InstrumentSnapshot(
        instrument=SPY,
        source_id="price-US_SPY",
        provenance=PROV,
        status=DataStatus.OK,
        last_close=100.0,
        last_observed_at=NOW,
        change_1w_pct=1.5,
        issues=["luka"],
    )


def _macro_snapshot() -> MacroSnapshot:
    series = MacroSeries(
        id="CPI", name="CPI", frequency=MacroFrequency.MONTHLY, stale_after_days=75
    )
    return MacroSnapshot(
        series=series, source_id="macro-CPI", provenance=PROV, status=DataStatus.STALE
    )


def test_full_run_lifecycle(repo: SqlRepository, engine: Engine) -> None:
    run_id = _run(repo)
    snap_ids = repo.add_instrument_snapshots(
        run_id, [_instrument_snapshot()], rules_version="r1", created_at=NOW
    )
    repo.add_macro_snapshots(run_id, [_macro_snapshot()], rules_version="r1", created_at=NOW)
    report_id = repo.add_report(
        run_id,
        ReportRecord(
            report_week="2026-W44",
            kind="weekly",
            complete=True,
            subject="Brief",
            markdown="# Raport zażółć",
            html="<p>Raport</p>",
            draft={"summary": []},
            errors=[],
            created_at=NOW,
        ),
    )
    repo.add_delivery(
        report_id, DeliveryRecord(attempted_at=NOW, status="sent", recipients_count=1)
    )
    repo.add_error(run_id, stage="news", message="HTTP 429", created_at=NOW)
    repo.finish_run(run_id, RunFinish(status="ok", finished_at=NOW, model="m", llm_cost=0.01))

    assert len(snap_ids) == 1 and isinstance(snap_ids[0], uuid.UUID)
    runs = repo.recent_runs()
    assert [(r.id, r.status, r.model) for r in runs] == [(run_id, "ok", "m")]
    with engine.connect() as conn:
        snap = conn.execute(select(InstrumentSnapshotRow)).one()
        report = conn.execute(select(ReportRow)).one()
    assert snap.id == snap_ids[0]
    assert snap.issues == ["luka"]
    assert snap.provenance["provider"] == "test"
    assert snap.rules_version == "r1"
    assert report.markdown == "# Raport zażółć"


def test_each_run_adds_new_records(repo: SqlRepository, engine: Engine) -> None:
    for _ in range(2):
        run_id = _run(repo)
        repo.add_instrument_snapshots(
            run_id, [_instrument_snapshot()], rules_version="r1", created_at=NOW
        )
    assert _count(engine, RunRow) == 2
    assert _count(engine, InstrumentSnapshotRow) == 2


def test_append_only_records_have_no_update_or_delete_api() -> None:
    names = [n for n in dir(SqlRepository) if not n.startswith("_")]
    forbidden = [
        n
        for n in names
        if any(word in n for word in ("update", "delete", "remove", "replace"))
        and any(t in n for t in ("snapshot", "report", "delivery", "error"))
    ]
    assert forbidden == []


def test_finish_unknown_run_raises(repo: SqlRepository) -> None:
    with pytest.raises(StorageError, match="not found"):
        repo.finish_run(uuid.uuid4(), RunFinish(status="ok", finished_at=NOW))


def test_database_errors_do_not_leak_sql() -> None:
    engine = create_db_engine("sqlite://")  # no migrations: tables missing
    with pytest.raises(StorageError) as info:
        SqlRepository(engine).start_run(
            RunStart(report_week="W", mode="m", started_at=NOW, rules_version="r", config_hash="h")
        )
    assert str(info.value) == "database error: OperationalError"
