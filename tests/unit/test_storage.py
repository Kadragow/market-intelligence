# --- datetime handling ---------------------------------------------------------------


def test_datetimes_round_trip_as_aware_utc(repo: SqlRepository, engine: Engine) -> None:
    warsaw = timezone(timedelta(hours=1))
    repo.upsert_price_bars(
        [_bar(1, 1.0)], provider="t", fetched_at=datetime(2026, 10, 27, 13, 0, tzinfo=warsaw)
    )
    with engine.connect() as conn:
        row = conn.execute(select(PriceBarRow)).one()
    assert row.fetched_at == NOW
    assert row.fetched_at.tzinfo is UTC
    assert row.observed_at.tzinfo is UTC


