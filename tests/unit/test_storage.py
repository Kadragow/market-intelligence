def test_price_upsert_updates_instead_of_duplicating(repo: SqlRepository, engine: Engine) -> None:
    repo.upsert_price_bars([_bar(1, 1.0), _bar(2, 2.0)], provider="t", fetched_at=NOW)
    later = NOW + timedelta(days=1)
    repo.upsert_price_bars([_bar(2, 2.5), _bar(2, 2.6)], provider="t", fetched_at=later)
    assert _count(engine, PriceBarRow) == 2
    with engine.connect() as conn:
        row = conn.execute(select(PriceBarRow).where(PriceBarRow.close > 2)).one()
    assert row.close == 2.6
    assert row.fetched_at == later


def test_missing_values_are_stored_as_null(repo: SqlRepository, engine: Engine) -> None:
    repo.upsert_macro_observations(
        [MacroObservation(series_id="X", observed_at=NOW, value=None)],
        provider="fred",
        fetched_at=NOW,
    )
    with engine.connect() as conn:
        value = conn.execute(text("select value from macro_observations")).scalar_one()
    assert value is None


def test_news_is_inserted_once_and_first_fetch_kept(repo: SqlRepository, engine: Engine) -> None:
    assert repo.add_news([_news(), _news()]) == 1
    assert repo.add_news([_news(NOW + timedelta(days=1))]) == 0
    with engine.connect() as conn:
        row = conn.execute(select(NewsItemRow)).one()
    assert row.fetched_at == NOW


