def _count(engine: Engine, model: type) -> int:
    with engine.connect() as conn:
        return int(conn.execute(select(func.count()).select_from(model)).scalar_one())


def _bar(day: int, close: float) -> PriceBar:
    return PriceBar(
        instrument_id="US_SPY", observed_at=datetime(2026, 10, day, tzinfo=UTC), close=close
    )


def _news(fetched_at: datetime = NOW) -> NewsItem:
    return NewsItem(
        id=NewsItem.make_id("https://e.com/a"),
        title="Nagłówek",
        link="https://e.com/a",
        source_id="s",
        source_name="S",
        category="finance",
        published_at=NOW - timedelta(hours=1),
        fetched_at=fetched_at,
    )


def _run(repo: SqlRepository) -> uuid.UUID:
    return repo.start_run(
        RunStart(
            report_week="2026-W44",
            mode="live",
            started_at=NOW,
            rules_version="r1",
            config_hash="abc",
        )
    )


# --- migrations -------------------------------------------------------------------


def test_file_database_upgrade_and_schema_check(tmp_path: Path) -> None:
    engine = create_db_engine(f"sqlite:///{tmp_path / 'sub' / 'mi.db'}")
    with pytest.raises(SchemaNotCurrentError, match="mi db upgrade"):
        ensure_schema_current(engine)
    upgrade(engine)
    ensure_schema_current(engine)
    upgrade(engine)  # idempotent
    assert (tmp_path / "sub" / "mi.db").is_file()
    assert head_revision() == "0001"


def test_models_match_migrations(engine: Engine) -> None:
    cfg = alembic_config(engine)
    with engine.begin() as conn:
        cfg.attributes["connection"] = conn
        command.check(cfg)  # raises AutogenerateDiffsDetected on drift


